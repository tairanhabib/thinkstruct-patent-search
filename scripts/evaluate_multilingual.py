"""Does search work as well on foreign patents as on English ones? Writes eval_results.md.

Usage: python scripts/evaluate_multilingual.py [--index index]

Needs the parallel set in the index (scripts/make_parallel_set.py, then
`python cli.py ingest data/parallel`). The same inventions then exist in English, German
and Chinese.

Test: for each of those patents, take its first claim in English and search for it. The
claims themselves are not candidates, so the right answer is the same patent's abstract
or description. A patent counts as found at the rank where it appears. The only thing
that changes between columns is the language the target patent is written in.
"""
import argparse
import os
import sys

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from src import embed  # noqa: E402
from src.search import Index, search  # noqa: E402

LANGUAGE_NAMES = {"en": "English", "de": "German", "zh": "Chinese"}


def first_claim(index, doc_number):
    row = index.con.execute(
        "SELECT s.text FROM passages s JOIN patents p ON p.id = s.patent_id "
        "WHERE p.doc_number = ? AND s.kind = 'claim' ORDER BY s.ord LIMIT 1", (doc_number,)).fetchone()
    return row[0] if row else None


def reciprocal_ranks(index, queries, targets, candidates, mode):
    """1 / rank of the target patent for each query (0 when it is not returned at all)."""
    out = []
    for query, target in zip(queries, targets):
        results = search(query, mode=mode, passage_types=["abstract", "description"], restrict_docs=candidates,
                         top_k=len(candidates), translate_results=False, index=index)
        found = [i for i, result in enumerate(results, 1) if result["doc_number"] == target]
        out.append(1.0 / found[0] if found else 0.0)
    return np.array(out)


def summarize(rr):
    return {"recall@1": float((rr == 1).mean()), "recall@10": float((rr >= 0.1).mean()), "mrr": float(rr.mean())}


def gap_interval(rr, baseline, rounds=2000):
    """95% paired bootstrap interval for the difference in mean reciprocal rank (language minus English)."""
    rng = np.random.default_rng(0)
    difference = rr - baseline
    samples = rng.choice(difference, (rounds, len(difference))).mean(axis=1)
    return float(np.percentile(samples, 2.5)), float(np.percentile(samples, 97.5))


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--index")
    parser.add_argument("--out", default="eval_results.md")
    args = parser.parse_args()
    index = Index(args.index)

    copies = {}  # language -> {original document number: copy document number}
    for doc in index.patent_ids:
        base, _, suffix = doc.rpartition("-")
        if suffix in ("DE", "ZH") and base in index.patent_ids:
            copies.setdefault(suffix.lower(), {})[base] = doc
    if not copies:
        raise SystemExit("no parallel set in the index: run scripts/make_parallel_set.py and ingest data/parallel first")
    originals = sorted(set.intersection(*(set(c) for c in copies.values())))
    copies["en"] = {doc: doc for doc in originals}
    languages = ["en"] + sorted(k for k in copies if k != "en")
    all_copies = {copy for by_original in copies.values() for copy in by_original.values()}
    distractors = [doc for doc in index.patent_ids if doc not in all_copies]  # the other English patents
    queries = [first_claim(index, doc) for doc in originals]

    out = ["# Multilingual evaluation\n",
           "Generated by `python scripts/evaluate_multilingual.py`.\n",
           f"- {len(originals)} patents exist in English (original), German and Chinese (machine translated copies).",
           "- Query: the first claim of each patent, in English, as stored (not the title, not the abstract).",
           "- Candidates: abstracts and description paragraphs only. Claims are excluded, so a patent cannot be found through the query text itself.",
           "- Right answer: the same patent, in the language of the column.",
           f"- Embedding model: `{embed.MODEL_NAME}`. Recall at k is the share of queries whose patent is in the top k.",
           "- The interval is a 95% paired bootstrap interval on the difference in mean reciprocal rank against English.\n"]

    settings = [
        ("Alone", f"Candidates are only the {len(originals)} test patents in one language.",
         lambda language: list(copies[language].values())),
        ("Mixed", f"Candidates are the {len(originals)} test patents in one language plus the {len(distractors)} other English "
         "patents. A foreign patent has to beat English distractors for an English query, so this also measures language bias.",
         lambda language: list(copies[language].values()) + distractors),
    ]
    table = {}
    for name, description, candidates_for in settings:
        out += [f"## {name}\n", description + "\n",
                "| Mode | Target language | Recall at 1 | Recall at 10 | Mean reciprocal rank | Gap to English (MRR) | 95% interval |",
                "| --- | --- | --- | --- | --- | --- | --- |"]
        for mode in ("semantic", "keyword", "hybrid"):
            baseline = None
            for language in languages:
                targets = [copies[language][doc] for doc in originals]
                rr = reciprocal_ranks(index, queries, targets, candidates_for(language), mode)
                baseline = rr if baseline is None else baseline
                s = summarize(rr)
                table[(name, mode, language)] = s
                gap = "" if language == "en" else f"{s['mrr'] - baseline.mean():+.3f}"
                interval = "" if language == "en" else "{:+.3f} to {:+.3f}".format(*gap_interval(rr, baseline))
                out.append(f"| {mode} | {LANGUAGE_NAMES.get(language, language)} | {s['recall@1']:.2f} | {s['recall@10']:.2f} "
                           f"| {s['mrr']:.3f} | {gap} | {interval} |")
                print(out[-1], flush=True)
        out.append("")

    # the other direction: a foreign query against English patents
    out += ["## Foreign query, English patents\n",
            f"The query is the first claim of the translated copy. Candidates are all {len(originals) + len(distractors)} original "
            "English patents (abstract and description). Semantic mode only: keyword search needs English words.\n",
            "| Query language | Recall at 1 | Recall at 10 | Mean reciprocal rank |", "| --- | --- | --- | --- |"]
    english_pool = originals + distractors
    for language in languages:
        foreign_queries = [first_claim(index, copies[language][doc]) for doc in originals]
        s = summarize(reciprocal_ranks(index, foreign_queries, originals, english_pool, "semantic"))
        out.append(f"| {LANGUAGE_NAMES.get(language, language)} | {s['recall@1']:.2f} | {s['recall@10']:.2f} | {s['mrr']:.3f} |")
        print(out[-1], flush=True)

    # facts that help explain a gap
    out += ["\n## Diagnostics\n", "| Language | Patents | Detected as that language | Vectors | Vectors longer than the model input (512 tokens) |",
            "| --- | --- | --- | --- | --- |"]
    tokenizer = embed.model().tokenizer
    for language in languages:
        docs = list(copies[language].values())
        marks = ",".join("?" * len(docs))
        detected = index.con.execute(f"SELECT COUNT(*) FROM patents WHERE language = ? AND doc_number IN ({marks})",
                                     [language] + docs).fetchone()[0]
        rows = index.con.execute(
            "SELECT s.id, s.kind, s.number_inferred, s.text, p.title FROM passages s JOIN patents p ON p.id = s.patent_id "
            f"WHERE p.doc_number IN ({marks})", docs).fetchall()
        shortest, window = embed.limits(language)
        pieces = []
        for row in rows:
            if len(row["text"]) >= shortest:
                text = f"{row['title']}: {row['text']}" if row["kind"] == "claim" and row["number_inferred"] else row["text"]
                pieces += embed.windows(text, window)
        too_long = sum(len(ids) > embed.MAX_TOKENS for ids in tokenizer(["passage: " + p for p in pieces], truncation=False)["input_ids"])
        out.append(f"| {LANGUAGE_NAMES.get(language, language)} | {len(docs)} | {detected} | {len(pieces)} | {too_long} |")
    with open(args.out, "w", encoding="utf-8") as handle:
        handle.write("\n".join(out) + "\n")
    print(f"\nwrote {args.out}")


if __name__ == "__main__":
    main()
