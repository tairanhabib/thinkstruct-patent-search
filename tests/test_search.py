def test_keyword_filter_needs_every_keyword_and_matches_whole_words(build_index):
    """Was `..._uses_word_stems`. A stemmer files generator, general, generally and generic under one stem,
    so the filter passed patents that do not contain the keyword. It now matches the word itself, and its
    plain plural or singular."""
    index, _ = build_index([COMPLETE, OTHER, GENERIC])
    assert docs(search("vehicle part", keywords="sensors pressure", index=index)) == ["D-COMPLETE"]  # plural is the same word
    assert search("vehicle part", keywords="pressure grooves", index=index) == []
    assert search(keywords="generator", index=index) == [] and search(keywords="general", index=index) == []
    assert docs(search(keywords="generated", index=index)) == ["D-GENERIC"]
    assert docs(search(keywords="brackets", index=index)) == ["D-GENERIC"]
    assert docs(search("generators", mode="keyword", index=index)) == ["D-GENERIC"]  # ranking still uses stems


